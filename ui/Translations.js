function text(lang, key, values) {
    var table = TEXT[lang] || TEXT.pt
    var value = table[key] || TEXT.pt[key] || key
    if (!values)
        return value
    for (var name in values)
        value = value.replace("{" + name + "}", values[name])
    return value
}

